# WHAT: creates the local .env with fresh random secrets for Keycloak (run once).
# WHY:  no secret is committed to the repository; each machine makes its own.
#       Safe to re-run: an existing .env is left untouched.
#
#   powershell -ExecutionPolicy Bypass -File scripts\setup.ps1

$envFile = Join-Path $PSScriptRoot "..\.env"
if (Test-Path $envFile) {
    Write-Host ".env already exists; nothing to do."
    exit 0
}

function New-Secret {
    $bytes = New-Object byte[] 32
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    return ([System.BitConverter]::ToString($bytes) -replace '-', '').ToLower()
}

@"
# Local secrets for docker compose. Generated by scripts/setup; never commit this file.
EASYTRAVEL_OIDC_SECRET=$(New-Secret)
KEYCLOAK_ADMIN_PASSWORD=$(New-Secret)
"@ | Set-Content -Path $envFile -Encoding ascii

Write-Host "Created .env with new random secrets."
